import logging
import re
from typing import Any

logger = logging.getLogger(__name__)


class ReportEngine:
    """Compiles High-Level Design (HLD.md) and Low-Level Design (LLD.md) Markdown documents."""

    def generate_hld(
        self,
        project_name: str,
        extracted_reqs: dict[str, Any],
        nodes: list[dict[str, Any]],
        edges: list[dict[str, Any]],
        cost_report: dict[str, Any] | None,
        security_report: dict[str, Any] | None,
        explanation: dict[str, Any] | None,
    ) -> str:
        app_type = extracted_reqs.get("application_type", "Web Application").replace("_", " ").title()
        cloud = str(extracted_reqs.get("cloud", "AWS")).upper()
        region = extracted_reqs.get("region", "us-east-1")
        cost = cost_report.get("estimated_monthly_cost", "N/A") if cost_report else "N/A"
        risk = security_report.get("risk_level", "LOW") if security_report else "LOW"

        node_list_md = ""
        for n in nodes:
            label = n.get("data", {}).get("label") or n.get("id")
            srv = n.get("data", {}).get("service") or n.get("type") or "service"
            node_list_md += f"- **{label}** (`{srv}`)\n"

        reasons_md = ""
        if explanation and explanation.get("chosen_because"):
            for r in explanation["chosen_because"]:
                reasons_md += f"- {r}\n"

        return f'''# High-Level Design (HLD): {project_name}

> **Generated by DOPA Architecture System**
> **Cloud Provider:** {cloud} ({region}) | **Target App:** {app_type}

---

## 1. Executive Summary

This High-Level Design document specifies the production architecture for **{project_name}**. 
The system is designed as a secure, fault-tolerant, cloud-native architecture on {cloud} ({region}).

- **Estimated Monthly Spend:** ${cost}/month
- **Security Assessment Risk Level:** `{risk}`
- **Deployment Strategy:** Automated Infrastructure-as-Code via Terraform

---

## 2. Business & Technical Requirements

| Parameter | Requirement |
|---|---|
| **Application Type** | {app_type} |
| **Cloud Provider** | {cloud} |
| **Region** | {region} |
| **Traffic Target** | {extracted_reqs.get('traffic', 'Moderate')} |
| **Availability Target** | {extracted_reqs.get('availability', 'High')} |
| **Database Preference** | {extracted_reqs.get('database', 'Relational PostgreSQL')} |

---

## 3. Architecture Overview & Components

The architecture comprises the following cloud service components:

{node_list_md}

### Design Rationale & Tradeoffs
{reasons_md if reasons_md else "- Designed for high availability and low operational overhead."}

---

## 4. Cost & Security Summary

- **Monthly Cost Estimate:** ${cost} USD
- **Security Compliance:** HIPAA Eligible, SOC2 Compatible
- **Primary Security Posture:** Private subnet network isolation, KMS default encryption, zero public DB access.

---

*Document compiled automatically by DOPA Report Engine.*
'''

    def generate_lld(
        self,
        project_name: str,
        nodes: list[dict[str, Any]],
        edges: list[dict[str, Any]],
        terraform_files: dict[str, str] | None,
        validation_report: dict[str, Any] | None,
    ) -> str:
        tf_structure_md = ""
        if terraform_files:
            for fname in terraform_files.keys():
                tf_structure_md += f"- `{fname}`\n"
        else:
            tf_structure_md = "- `main.tf`\n- `provider.tf`\n- `variables.tf`\n- `outputs.tf`\n"

        edge_list_md = ""
        for e in edges:
            src = e.get("source")
            tgt = e.get("target")
            rel = e.get("label") or "connects to"
            edge_list_md += f"- `{src}` ──[{rel}]──► `{tgt}`\n"

        vpc_cidr = "172.16.0.0/16"
        if terraform_files:
            variables_tf = terraform_files.get("variables.tf", "")
            match = re.search(r'variable\s+"vpc_cidr"\s*\{[^}]*default\s*=\s*"([^"]+)"', variables_tf, re.S)
            if match:
                vpc_cidr = match.group(1)

        return f'''# Low-Level Design (LLD): {project_name}

> **Generated by DOPA Architecture System**
> **Artifact Type:** Technical Infrastructure Specification

---

## 1. Network Topology & Subnet Design

The network layer uses an AWS VPC with multi-AZ public and private subnets.

- **VPC CIDR Block:** `{vpc_cidr}`
- **Public Subnets (Ingress / ALB):** `10.0.101.0/24`, `10.0.102.0/24`
- **Private Subnets (Compute & Data):** `10.0.1.0/24`, `10.0.2.0/24`
- **NAT Gateway Strategy:** High-availability regional NAT configuration

---

## 2. Component Interconnections & Dependency Graph

{edge_list_md if edge_list_md else "- Standard web tier to database connection flow."}

---

## 3. Infrastructure-as-Code File Package Structure

The generated Terraform HCL code is structured into modular components:

{tf_structure_md}

---

## 4. Security Group Rules & IAM Specifications

| Security Group | Ingress Rules | Egress Rules | Target |
|---|---|---|---|
| `alb_sg` | Port 80 / 443 (0.0.0.0/0) | All outbound | ALB Load Balancer |
| `app_sg` | Port 8080 from `alb_sg` | All outbound | ECS Fargate Tasks |
| `db_sg` | Port 5432 from `app_sg` | Blocked | RDS Database Instance |

---

*Document compiled automatically by DOPA Report Engine.*
'''
