import logging
import re
from typing import Any

from backend.services.knowledge_loader import KnowledgeLoader

logger = logging.getLogger(__name__)


class TerraformEngine:
    """Generates production-grade, modular HCL Terraform files from an ArchitectureGraph."""

    def __init__(self) -> None:
        loader = KnowledgeLoader()
        self.catalog = loader.get("terraform-module-catalog.json") or []
        self.aws_schemas = loader.get("aws-resource-schemas.json") or {}

    def generate(
        self,
        graph_nodes: list[dict[str, Any]],
        graph_edges: list[dict[str, Any]],
        project_name: str = "dopa-app",
        region: str = "us-east-1",
        environment: str = "prod",
    ) -> dict[str, str]:
        """Generates a dict of filename -> HCL code string."""
        # Sanitize project name to valid Terraform identifier/slug
        clean_name = re.sub(r"[^a-zA-Z0-9-]", "-", project_name.lower()).strip("-")
        if not clean_name or clean_name == "new-architecture":
            clean_name = "ecommerce-platform"

        # Determine environment-specific CIDR
        if environment == "dev":
            vpc_cidr = "10.10.0.0/16"
            private_subnets = '["10.10.1.0/24", "10.10.2.0/24"]'
            public_subnets = '["10.10.101.0/24", "10.10.102.0/24"]'
        elif environment == "enterprise":
            vpc_cidr = "10.100.0.0/16"
            private_subnets = '["10.100.1.0/24", "10.100.2.0/24"]'
            public_subnets = '["10.100.101.0/24", "10.100.102.0/24"]'
        else:
            vpc_cidr = "172.16.0.0/16"
            private_subnets = '["172.16.1.0/24", "172.16.2.0/24"]'
            public_subnets = '["172.16.101.0/24", "172.16.102.0/24"]'

        services_present = set()
        for node in graph_nodes:
            srv = node.get("data", {}).get("service") or node.get("type") or node.get("id")
            if srv:
                services_present.add(srv.lower())

        files = {}
        files["provider.tf"] = self._build_provider_tf(region)
        files["variables.tf"] = self._build_variables_tf(clean_name, region, vpc_cidr, environment)
        files["outputs.tf"] = self._build_outputs_tf(services_present)
        files["terraform.tfvars"] = self._build_tfvars(clean_name, region, vpc_cidr, environment)
        files["main.tf"] = self._build_main_tf(graph_nodes, graph_edges, services_present, clean_name, private_subnets, public_subnets)

        return files

    def _build_provider_tf(self, region: str) -> str:
        return f'''# Auto-generated by DOPA Architecture & Terraform Engine
terraform {{
  required_version = ">= 1.5.0"
  required_providers {{
    aws = {{
      source  = "hashicorp/aws"
      version = "~> 5.0"
    }}
  }}

  # Remote State Configuration (Recommended for Team & Production Deployments)
  # backend "s3" {{
  #   bucket         = "dopa-terraform-state-bucket"
  #   key            = "environments/prod/terraform.tfstate"
  #   region         = "{region}"
  #   dynamodb_table = "dopa-terraform-locks"
  #   encrypt        = true
  # }}
}}

provider "aws" {{
  region = var.aws_region

  default_tags {{
    tags = {{
      Project     = var.project_name
      Environment = var.environment
      ManagedBy   = "DOPA-IaC-Engine"
      Owner       = "DevOps-Team"
      CostCenter  = "Engineering-Cloud"
    }}
  }}
}}
'''

    def _build_variables_tf(self, project_name: str, region: str, vpc_cidr: str, environment: str) -> str:
        return f'''variable "project_name" {{
  description = "Name of the application project"
  type        = string
  default     = "{project_name}"
}}

variable "environment" {{
  description = "Deployment environment (dev, staging, prod)"
  type        = string
  default     = "{environment}"
}}

variable "aws_region" {{
  description = "Target AWS region"
  type        = string
  default     = "{region}"
}}

variable "vpc_cidr" {{
  description = "CIDR block for main VPC"
  type        = string
  default     = "{vpc_cidr}"
}}

variable "cost_center" {{
  description = "Cost Center allocation tag"
  type        = string
  default     = "Engineering-Cloud"
}}
'''

    def _build_tfvars(self, project_name: str, region: str, vpc_cidr: str, environment: str) -> str:
        return f'''project_name = "{project_name}"
environment  = "{environment}"
aws_region   = "{region}"
vpc_cidr     = "{vpc_cidr}"
cost_center  = "Engineering-Cloud"
'''

    def _build_outputs_tf(self, services: set[str]) -> str:
        outputs = []
        outputs.append('''output "vpc_id" {
  description = "ID of the VPC"
  value       = module.vpc.vpc_id
}''')
        if "alb" in services:
            outputs.append('''output "alb_dns_name" {
  description = "DNS Name of the Application Load Balancer"
  value       = module.alb.dns_name
}''')
        if "rds" in services:
            outputs.append('''output "rds_endpoint" {
  description = "Database Connection Endpoint"
  value       = module.rds.db_instance_endpoint
  sensitive   = true
}''')
        if "redis" in services or "elasticache" in services:
            outputs.append('''output "elasticache_endpoint" {
  description = "ElastiCache Redis Connection Endpoint"
  value       = module.redis.primary_endpoint_address
  sensitive   = true
}''')
        if "s3" in services:
            outputs.append('''output "s3_bucket_name" {
  description = "Name of the primary S3 media bucket"
  value       = module.s3.s3_bucket_id
}''')

        return "\n\n".join(outputs) + "\n"

    def _build_main_tf(
        self,
        nodes: list[dict[str, Any]],
        edges: list[dict[str, Any]],
        services: set[str],
        project_name: str,
        private_subnets: str,
        public_subnets: str,
    ) -> str:
        blocks = []
        blocks.append('''# --- Dynamic Availability Zone Discovery ---
data "aws_availability_zones" "available" {
  state = "available"
}''')

        blocks.append('\n# --- Core Networking (VPC) ---')
        blocks.append(f'''module "vpc" {{
  source  = "terraform-aws-modules/vpc/aws"
  version = "5.1.0"

  name = "${{var.project_name}}-vpc"
  cidr = var.vpc_cidr

  azs             = slice(data.aws_availability_zones.available.names, 0, 2)
  private_subnets = {private_subnets}
  public_subnets  = {public_subnets}

  enable_nat_gateway   = true
  single_nat_gateway   = var.environment != "prod" ? true : false
  enable_dns_hostnames = true
}}''')

        if "kms" in services or "security" in services:
            blocks.append('\n# --- Security & Encryption (KMS) ---')
            blocks.append('''module "kms" {
  source  = "terraform-aws-modules/kms/aws"
  version = "2.1.0"

  description             = "KMS Key for ${var.project_name} data encryption"
  deletion_window_in_days = 7
  enable_key_rotation     = true
}''')

        if "alb" in services:
            blocks.append('\n# --- Load Balancing (ALB) ---')
            blocks.append('''module "alb" {
  source  = "terraform-aws-modules/alb/aws"
  version = "9.2.0"

  name               = "${var.project_name}-alb"
  load_balancer_type = "application"
  vpc_id             = module.vpc.vpc_id
  subnets            = module.vpc.public_subnets

  security_group_ingress_rules = {
    all_http = {
      from_port   = 80
      to_port     = 80
      ip_protocol = "tcp"
      description = "HTTP web traffic"
      cidr_ipv4   = "0.0.0.0/0"
    }
  }
}''')

        if "ecs" in services:
            blocks.append('\n# --- Compute Layer (ECS Fargate) ---')
            blocks.append('''module "ecs" {
  source  = "terraform-aws-modules/ecs/aws"
  version = "5.2.0"

  cluster_name = "${var.project_name}-cluster"

  fargate_capacity_providers = {
    FARGATE = {
      default_capacity_provider_strategy = {
        weight = 100
      }
    }
  }
}''')

        if "rds" in services:
            blocks.append('\n# --- Database Layer (RDS PostgreSQL) ---')
            blocks.append('''module "rds" {
  source  = "terraform-aws-modules/rds/aws"
  version = "6.3.0"

  identifier = "${var.project_name}-db"

  engine               = "postgres"
  engine_version       = "15.4"
  family               = "postgres15"
  instance_class       = "db.t4g.medium"
  allocated_storage    = 20
  max_allocated_storage = 100

  db_name  = "dopa_db"
  username = "dopa_admin"
  port     = 5432

  multi_az               = var.environment == "prod" ? true : false
  db_subnet_group_name   = module.vpc.database_subnet_group_name
  vpc_security_group_ids = [module.vpc.default_security_group_id]

  skip_final_snapshot = true
}''')

        if "redis" in services or "elasticache" in services:
            blocks.append('\n# --- Caching Layer (ElastiCache Redis) ---')
            blocks.append('''module "redis" {
  source  = "terraform-aws-modules/elasticache/aws"
  version = "1.2.0"

  cluster_id           = "${var.project_name}-redis"
  engine               = "redis"
  engine_version       = "7.0"
  node_type            = "cache.t4g.small"
  num_cache_nodes      = 1
  parameter_group_name = "default.redis7"
  port                 = 6379

  subnet_ids         = module.vpc.private_subnets
  security_group_ids = [module.vpc.default_security_group_id]
}''')

        if "s3" in services:
            blocks.append('\n# --- Object Storage (S3 Media Bucket) ---')
            blocks.append('''module "s3" {
  source  = "terraform-aws-modules/s3-bucket/aws"
  version = "3.15.0"

  bucket = "${var.project_name}-media-assets"

  control_object_ownership = true
  object_ownership         = "BucketOwnerPreferred"

  versioning = {
    enabled = true
  }
}''')

        return "\n\n".join(blocks) + "\n"
